<?php
/**
 * Translations for the admin React apps (Settings, Integrations, the shared
 * admin-common layer and the ReadyLaunch onboarding wizard).
 *
 * Each handle is registered with wp_set_script_translations(), the WordPress
 * standard. `grunt makepot` also writes the standard Jed JSON files
 * (languages/buddyboss-{locale}-{md5}.json).
 *
 * At runtime the React admin is served from the `buddyboss` translations PHP
 * actually loaded, read through translate() / _n(), so it always matches the
 * PHP admin: the bundled .mo, a Loco Translate or WPML catalog layered over it,
 * a `plugin_locale` override and the gettext filters all apply the same way.
 * The bundled JSON is therefore skipped for these handles; a JSON file a site
 * places in wp-content/languages/ is still honoured.
 *
 * @package BuddyBoss\Core\Administration
 * @since BuddyBoss [BBVERSION]
 */

defined( 'ABSPATH' ) || exit;

/**
 * Attach the `buddyboss` script translations to an admin React handle.
 *
 * @since BuddyBoss [BBVERSION]
 *
 * @param string $handle Registered script handle.
 *
 * @return void
 */
function bb_admin_set_script_translations( $handle ) {
	if ( function_exists( 'wp_set_script_translations' ) ) {
		wp_set_script_translations( $handle, 'buddyboss', buddypress()->plugin_dir . 'languages' );
	}
}

/**
 * Get the strings each admin React handle renders.
 *
 * Generated by bin/admin-js-i18n.js during `grunt makepot`.
 *
 * @since BuddyBoss [BBVERSION]
 *
 * @return array Handle => list of array( singular, context, plural ).
 */
function bb_admin_get_script_translation_strings() {
	static $strings = null;

	if ( null === $strings ) {
		$file    = buddypress()->plugin_dir . 'bp-core/admin/bb-settings/script-translation-strings.php';
		$strings = file_exists( $file ) ? include $file : array();
		$strings = is_array( $strings ) ? $strings : array();
	}

	return $strings;
}

/**
 * Get one sample count per plural form of the loaded `buddyboss` translations.
 *
 * _n() takes a count, not a form index, so each form is looked up with a count
 * that selects it under the catalog's Plural-Forms rule.
 *
 * @since BuddyBoss [BBVERSION]
 *
 * @return int[] Plural form index => count.
 */
function bb_admin_get_script_translation_plural_samples() {
	$translations = get_translations_for_domain( 'buddyboss' );
	$headers      = is_array( $translations->headers ) ? $translations->headers : array();
	$header       = ! empty( $headers['Plural-Forms'] ) ? $headers['Plural-Forms'] : '';
	$nplurals     = 2;
	$expression   = 'n != 1';

	if ( preg_match( '/^\s*nplurals\s*=\s*(\d+)\s*;\s*plural\s*=\s*(.+?)\s*;?\s*$/', $header, $matches ) ) {
		$nplurals   = max( 1, (int) $matches[1] );
		$expression = $matches[2];
	}

	if ( ! class_exists( 'Plural_Forms' ) ) {
		require_once ABSPATH . WPINC . '/pomo/plural-forms.php';
	}

	try {
		$plural_forms = new Plural_Forms( $expression );
	} catch ( Exception $e ) {
		$nplurals     = 2;
		$plural_forms = new Plural_Forms( 'n != 1' );
	}

	$samples = array();
	$found   = 0;
	for ( $n = 0; $n <= 1000 && $found < $nplurals; $n++ ) {
		$index = (int) $plural_forms->get( $n );

		if ( $index < $nplurals && ! isset( $samples[ $index ] ) ) {
			$samples[ $index ] = $n;
			++$found;
		}
	}

	ksort( $samples );

	return $samples;
}

/**
 * Build the Jed locale data for an admin React handle from the loaded
 * `buddyboss` translations.
 *
 * @since BuddyBoss [BBVERSION]
 *
 * @param string $handle Script handle.
 *
 * @return string|false JSON in the format of a make-json file, false when
 *                      nothing is translated (e.g. an English site).
 */
function bb_admin_get_script_translations_from_mo( $handle ) {
	static $cache = array();

	$domain  = 'buddyboss';
	$locale  = determine_locale();
	$strings = bb_admin_get_script_translation_strings();

	if ( empty( $strings[ $handle ] ) ) {
		return false;
	}

	if ( isset( $cache[ $handle ][ $locale ] ) ) {
		return $cache[ $handle ][ $locale ];
	}

	$data    = array();
	$samples = null;

	foreach ( $strings[ $handle ] as $item ) {
		list( $singular, $context, $plural ) = array_pad( (array) $item, 3, '' );

		$key = '' !== $context ? $context . "\4" . $singular : $singular;

		// Looked up exactly as PHP __() / _x() / _n() / _nx() would: first-match
		// across layered catalogs, and through the gettext filters (WPML).
		if ( '' === $plural ) {
			// phpcs:ignore WordPress.WP.I18n.LowLevelTranslationFunction, WordPress.WP.I18n.NonSingularStringLiteralText, WordPress.WP.I18n.NonSingularStringLiteralContext
			$translated = '' !== $context ? translate_with_gettext_context( $singular, $context, 'buddyboss' ) : translate( $singular, 'buddyboss' );

			if ( $translated !== $singular ) {
				$data[ $key ] = array( $translated );
			}
			continue;
		}

		if ( null === $samples ) {
			$samples = bb_admin_get_script_translation_plural_samples();
		}

		$forms      = array();
		$translated = false;

		// Slot k must hold form k (Jed reads entry[ plural_index( n ) ]). A form no
		// integer count selects (e.g. a fraction form) gets a placeholder copy so
		// the later forms keep their slots.
		for ( $index = 0, $last = max( array_keys( $samples ) ); $index <= $last; $index++ ) {
			if ( ! isset( $samples[ $index ] ) ) {
				$forms[ $index ] = $index > 0 ? $forms[ $index - 1 ] : $singular;
				continue;
			}

			$count = $samples[ $index ];
			// phpcs:ignore WordPress.WP.I18n.NonSingularStringLiteralSingle, WordPress.WP.I18n.NonSingularStringLiteralPlural, WordPress.WP.I18n.NonSingularStringLiteralContext
			$form            = '' !== $context ? _nx( $singular, $plural, $count, $context, 'buddyboss' ) : _n( $singular, $plural, $count, 'buddyboss' );
			$forms[ $index ] = $form;
			$translated      = $translated || ( 1 === $count ? $singular : $plural ) !== $form;
		}

		if ( $translated ) {
			$data[ $key ] = $forms;
		}
	}

	if ( empty( $data ) ) {
		$cache[ $handle ][ $locale ] = false;

		return false;
	}

	$translations = get_translations_for_domain( $domain );
	$headers      = is_array( $translations->headers ) ? $translations->headers : array();
	$plural_forms = ! empty( $headers['Plural-Forms'] ) ? $headers['Plural-Forms'] : 'nplurals=2; plural=(n != 1);';

	$cache[ $handle ][ $locale ] = wp_json_encode(
		array(
			'domain'      => 'messages',
			'locale_data' => array(
				// Union, not array_merge(): numeric msgids such as "404" must keep their keys.
				'messages' => array(
					'' => array(
						'domain'       => 'messages',
						'lang'         => $locale,
						'plural-forms' => $plural_forms,
					),
				) + $data,
			),
		)
	);

	return $cache[ $handle ][ $locale ];
}

/**
 * Serve admin React translations from the `buddyboss` translations PHP loaded.
 *
 * Core calls load_script_translations() once per candidate JSON path and a
 * last time with `$file = false` when none was found. For the admin React
 * handles this callback:
 * - skips the bundled JSON (languages/ inside the plugin): it cannot know which
 *   catalog PHP actually loaded (a Loco Translate or WPML layer, a
 *   `plugin_locale` override), so it could disagree with the PHP admin;
 * - leaves a JSON file the site placed in wp-content/languages/ to core;
 * - answers the final, not-found call from the loaded translations.
 *
 * @since BuddyBoss [BBVERSION]
 *
 * @param string|false|null $translations JSON-encoded translations, or null to continue.
 * @param string|false      $file         Candidate JSON path, false after the last candidate.
 * @param string            $handle       Script handle.
 * @param string            $domain       Text domain.
 *
 * @return string|false|null
 */
function bb_admin_script_translations_fallback( $translations, $file, $handle, $domain ) {
	if ( null !== $translations || 'buddyboss' !== $domain ) {
		return $translations;
	}

	$strings = bb_admin_get_script_translation_strings();
	if ( ! isset( $strings[ $handle ] ) ) {
		return $translations;
	}

	if ( false !== $file ) {
		$bundled = wp_normalize_path( trailingslashit( buddypress()->plugin_dir . 'languages' ) );

		return 0 === strpos( wp_normalize_path( $file ), $bundled ) ? false : $translations;
	}

	return bb_admin_get_script_translations_from_mo( $handle );
}
add_filter( 'pre_load_script_translations', 'bb_admin_script_translations_fallback', 10, 4 );
